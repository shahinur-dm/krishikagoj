export function buildArticles(bySlug, subsByCat = {}) {
  const articles = []
  let idx = 0

  Object.entries(categoryArticles).forEach(([catSlug, items]) => {
    const images = categoryImages[catSlug] || [img.field]
    const catSubs = subsByCat[catSlug] || []
    items.forEach(([title, excerpt, extra], i) => {
      idx += 1
      const sub = catSubs.length ? catSubs[i % catSubs.length] : null
      articles.push({
        title,
        slug: `${slugify(title, idx)}-${idx}`,
        excerpt,
        body: body(excerpt, extra || 'কৃষি খাতে এ উদ্যোগ কৃষকদের জন্য গুরুত্বপূর্ণ।'),
        image: images[i % images.length],
        author: authors[idx % authors.length],
        category: bySlug[catSlug]._id,
        subcategory: sub?._id || undefined,
        views: 500 + ((idx * 137) % 5000),
        publishedAt: new Date(Date.now() - idx * 3600000 * 4),
        headline: i < 2 && idx % 5 === 0,
        featured: i === 0,
        latest: true,
        popular: i < 3 && idx % 3 === 0,
        bigthumbnail: catSlug === 'projukti' && i === 0,
        firstSection: i < 2,
        firstSectionThumbnail: i === 0,
        categoryHomepage: i < 2,
        isPublished: true,
      })
    })
  })

  return articles
}

